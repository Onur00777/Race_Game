export const getLanguage = () => language;
export const setLanguage = code => { language = code === 'en' ? 'en' : 'tr'; };
export const local = pair => pair[language === 'en' ? 1 : 0];
export const t = (key, ...values) => local(messages[key]).replace(/\{(\d+)\}/g, (_, i) => values[i] ?? '');
export const translatedField = (item, field = 'name') => language === 'en' ? item[field + 'En'] ?? item[field] : item[field];
export const upper = text => text.toLocaleUpperCase(language === 'en' ? 'en' : 'tr-TR');
export const escapeHtml = input => String(input).replace(/[&<>"']/g, char =>
  ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
